// Generates src/lib/api/schema.d.ts from the control plane's OpenAPI document.
// The document comes from the control plane's own build (no database or network needed):
//   (cd ../control-plane && npm ci && npm run build) && npm run api:generate
// With --check it only compares, and fails if the committed file is stale (CI runs this).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "..", "src", "lib", "api", "schema.d.ts");
const dist = join(here, "..", "..", "control-plane", "dist");

const { buildApp } = await import(pathToFileURL(join(dist, "app.js")).href);
const { loadConfig } = await import(pathToFileURL(join(dist, "config.js")).href);
const config = loadConfig({
  RELAY_CONTROL_DSN: "host=unused",
  RELAY_JWT_SECRET: "x".repeat(32),
  RELAY_SECRET_KEYS: `k:${Buffer.alloc(32).toString("base64")}`,
  RELAY_VALKEY_URL: "redis://unused",
});
const unused = () => {
  throw new Error("not used while generating the API document");
};
const app = await buildApp({
  config,
  db: { query: unused },
  keyring: null,
  resolve: unused,
  loginLimiter: { retryAfter: unused, recordFailure: unused, recordSuccess: unused, close: async () => {} },
});
await app.ready();
const doc = app.swagger();
await app.close();

const header = "// Generated by scripts/generate-api.mjs from /api/v1/openapi.json. Do not edit.\n\n";
const text = header + astToString(await openapiTS(doc));
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== text) {
    console.error("src/lib/api/schema.d.ts is stale: run `npm run api:generate` and commit it.");
    process.exit(1);
  }
  console.log("schema.d.ts is up to date");
} else {
  writeFileSync(target, text);
  console.log(`wrote ${target}`);
}
